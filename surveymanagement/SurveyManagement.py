    def run(self):
        """Run the main plugin dialog"""
        # Show message that we're starting
        self.iface.messageBar().pushMessage(
            "Info", 
            "Opening Survey Management System...", 
            level=Qgis.Info, 
            duration=2
        )
        
        # Check psycopg2
        if not PSYCOPG2_AVAILABLE:
            reply = QMessageBox.question(
                self.iface.mainWindow(),
                "psycopg2 Missing",
                "The psycopg2 library is not installed.\n\n"
                "Would you like to continue in offline mode?\n"
                "(Database features will be disabled)",
                QMessageBox.Yes | QMessageBox.No
            )
            if reply == QMessageBox.No:
                return
            db_connection = None
        else:
            # Try to connect to database
            if not self.connect_db():
                # connect_db already handles user interaction
                return
            db_connection = self.db_connection
        
        # Import the dialog here to avoid circular imports
        try:
            from .SurveyManagement_dialog import SurveyManagementDialog
        except ImportError as e:
            self.iface.messageBar().pushMessage(
                "Error", 
                f"Could not load dialog: {str(e)}", 
                level=Qgis.Critical, 
                duration=5
            )
            QMessageBox.critical(
                self.iface.mainWindow(),
                "Plugin Error",
                f"Failed to load dialog module:\n{str(e)}\n\n"
                f"Please reinstall the plugin."
            )
            return
        
        # Create and show the dialog
        try:
            # Pass None for parent to make it a top-level window
            self.dialog = SurveyManagementDialog(self.iface.mainWindow(), db_connection)
            
            # Set window modality to ApplicationModal to block interaction with QGIS
            self.dialog.setWindowModality(Qt.ApplicationModal)
            
            # Show dialog
            self.dialog.show()
            
        except Exception as e:
            self.iface.messageBar().pushMessage(
                "Error", 
                f"Dialog error: {str(e)}", 
                level=Qgis.Critical, 
                duration=5
            )
            import traceback
            traceback.print_exc()
            QMessageBox.critical(
                self.iface.mainWindow(),
                "Plugin Error",
                f"An unexpected error occurred:\n\n{str(e)}\n\n"
                f"Please check the Python console for details."
            )